export function keywordsForPath(path: string, extra: readonly string[] = []): string[] {
  const normalised = path.startsWith("http")
    ? new URL(path).pathname.replace(/\/$/, "") || "/"
    : path.replace(/\/$/, "") || "/";

  const page = pageKeywords[normalised] ?? [];
  const parts = normalised.split("/").filter(Boolean);
  const slug = parts[1] ?? "";
  const fromSlug =
    normalised.startsWith("/solutions/") || normalised.startsWith("/industries/")
      ? [slug.replace(/-/g, " ")].filter(Boolean)
      : [];
  const solution = normalised.startsWith("/solutions/") ? solutionKeywords[slug] ?? [] : [];
  const industry = normalised.startsWith("/industries/") ? industryKeywords[slug] ?? [] : [];

  return uniqueKeywords([
    ...coreKeywords,
    ...geoKeywords,
    ...page,
    ...fromSlug,
    ...solution,
    ...industry,
    ...extra,
  ]);
}

function uniqueKeywords(items: string[]) {
  const seen = new Set<string>();
  const out: string[] = [];
  for (const item of items) {
    const key = item.trim().toLowerCase();
    if (!key || seen.has(key)) continue;
    seen.add(key);
    out.push(item.trim());
  }
  return out;
}

